-- Playtest Telemetry: core schema.
-- Conventions: TEXT (never VARCHAR(n)), timestamptz everywhere, RLS on with no policies
-- (the Worker uses the service role, which bypasses RLS).

create table public.projects (
  id                  uuid primary key default gen_random_uuid(),
  name                text not null,
  api_key_hash        text not null unique,          -- hex SHA-256 of the raw key; the raw key is never stored
  discord_webhook_url text null,
  retention_days      int  not null default 30 check (retention_days > 0),
  created_at          timestamptz not null default now()
);

create table public.sessions (
  id                uuid primary key,                -- generated by the client
  project_id        uuid not null references public.projects(id) on delete cascade,
  device_id         text not null,                   -- salted hash computed on the client
  tester_alias      text null,
  build_version     text not null default '',
  platform          text not null default '',
  device_model      text not null default '',
  os                text not null default '',
  gpu               text not null default '',
  system_memory_mb  int  null,
  screen            text not null default '',
  started_at        timestamptz not null,
  last_seen_at      timestamptz not null,
  ended_at          timestamptz null,
  end_reason        text null check (end_reason in ('clean', 'abnormal', 'unknown'))
);

-- One row per unique error per project. Stack traces live here once, never per event.
create table public.issues (
  id                 bigserial primary key,
  project_id         uuid not null references public.projects(id) on delete cascade,
  fingerprint        text not null,
  log_type           text not null,
  message_template   text not null,
  stack_trace        text not null default '',
  first_seen_at      timestamptz not null,
  last_seen_at       timestamptz not null,
  first_seen_build   text not null default '',
  last_seen_build    text not null default '',
  total_count        bigint not null default 0,
  unique (project_id, fingerprint)
);

-- High-volume table; keep rows small.
-- log_type values written by the Worker: Info | Warning | Error | Exception | Event
-- ('Event' = custom game / system events that carry event_name + props).
create table public.events (
  id            bigserial primary key,
  project_id    uuid not null references public.projects(id) on delete cascade,
  session_id    uuid not null references public.sessions(id) on delete cascade,
  client_ts     timestamptz not null,
  received_at   timestamptz not null default now(),
  log_type      text not null,
  fingerprint   text null,
  message       text not null default '',            -- truncated to 512 chars
  repeat_count  int  not null default 1,
  scene         text not null default '',
  context       jsonb null,
  breadcrumbs   jsonb null,                          -- only attached to Error/Exception
  event_name    text null,
  props         jsonb null
);

create table public.perf_samples (
  id                  bigserial primary key,
  project_id          uuid not null references public.projects(id) on delete cascade,
  session_id          uuid not null references public.sessions(id) on delete cascade,
  client_ts           timestamptz not null,
  received_at         timestamptz not null default now(),   -- used for retention; client clocks can be wrong
  scene               text not null default '',
  fps_avg             real not null,
  fps_p1_low          real not null,
  frame_ms_max        real not null,
  main_thread_ms_avg  real null,
  gc_alloc_kb         real null,
  used_mem_mb         int  not null,
  battery_level       real null,
  battery_status      text null,
  thermal_state       text null
);

create table public.bug_reports (
  id               bigserial primary key,
  project_id       uuid not null references public.projects(id) on delete cascade,
  session_id       uuid not null references public.sessions(id) on delete cascade,
  client_ts        timestamptz not null,
  tester_note      text not null default '',
  screenshot_path  text null,
  breadcrumbs      jsonb not null default '[]'::jsonb,
  context          jsonb not null default '{}'::jsonb
);

create index events_project_received_idx     on public.events (project_id, received_at desc);
create index events_session_ts_idx           on public.events (session_id, client_ts);
create index events_project_fp_received_idx  on public.events (project_id, fingerprint, received_at desc);
create index perf_samples_session_ts_idx     on public.perf_samples (session_id, client_ts);
create index perf_samples_project_ts_idx     on public.perf_samples (project_id, client_ts desc);
create index sessions_project_started_idx    on public.sessions (project_id, started_at desc);
create index sessions_project_device_idx     on public.sessions (project_id, device_id);
-- Support purge_old_data() and bug report lookups.
create index perf_samples_received_idx       on public.perf_samples (received_at);
create index bug_reports_session_idx         on public.bug_reports (session_id);

-- Security: RLS on, no policies for anon/authenticated.
alter table public.projects     enable row level security;
alter table public.sessions     enable row level security;
alter table public.issues       enable row level security;
alter table public.events       enable row level security;
alter table public.perf_samples enable row level security;
alter table public.bug_reports  enable row level security;

-- Defense in depth on Supabase: Supabase grants table privileges to anon/authenticated by
-- default. Revoke them (guarded so the migration also applies to plain Postgres).
do $$
declare
  r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on all tables in schema public from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
    end if;
  end loop;
end $$;
